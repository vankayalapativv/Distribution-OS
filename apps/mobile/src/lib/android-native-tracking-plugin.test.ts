import { existsSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { mobileRoot, read } from "./android-native-tracking.support";

describe("Android native tracking service (plugin generation)", () => {
  test("is reproducibly generated by an Expo config plugin", () => {
    const appConfig = read("app.json");
    const pluginPath = "plugins/withNativeTracking.js";
    const templateRoot = "plugins/native-tracking";

    expect(appConfig).toContain("./plugins/withNativeTracking");
    expect(existsSync(join(mobileRoot, pluginPath))).toBe(true);

    const plugin = existsSync(join(mobileRoot, pluginPath)) ? read(pluginPath) : "";
    expect(plugin).toContain("withAndroidManifest");
    expect(plugin).toContain("withAppBuildGradle");
    expect(plugin).toContain("withMainApplication");
    expect(plugin).toContain("withDangerousMod");

    for (const file of [
      "ForegroundLocationService.kt",
      "BootCompletedReceiver.kt",
      "NativeTrackingModule.kt",
      "NativeTrackingPackage.kt",
    ]) {
      expect(existsSync(join(mobileRoot, templateRoot, file))).toBe(true);
    }
  });

  test("keeps owned Kotlin sources free of known forward-compatibility warnings", () => {
    const service = read("plugins/native-tracking/ForegroundLocationService.kt");
    const nativePackage = read("plugins/native-tracking/NativeTrackingPackage.kt");

    expect(service).toContain("arrayOf<Any?>(");
    expect(nativePackage).toContain(
      '@Deprecated("Required by the ReactPackage interface")\n  override fun createNativeModules',
    );
  });

  // This checks the PREBUILT native manifest (android/…), which `expo prebuild`
  // generates and which is gitignored — so it's absent on a fresh CI checkout.
  // Skip it there; it runs wherever the native project has been generated.
  const manifestPath = join(mobileRoot, "android/app/src/main/AndroidManifest.xml");
  test.skipIf(!existsSync(manifestPath))("is registered as a location foreground service with boot recovery", () => {
    const manifest = read("android/app/src/main/AndroidManifest.xml");

    expect(manifest).toContain('android:name=".tracking.ForegroundLocationService"');
    expect(manifest).toContain('android:foregroundServiceType="location"');
    expect(manifest).toContain('android:name=".tracking.BootCompletedReceiver"');
    expect(manifest).toContain("android.intent.action.BOOT_COMPLETED");
  });
});
